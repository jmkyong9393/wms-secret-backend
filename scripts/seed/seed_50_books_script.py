with Session(engine) as db:
    existing_isbns = set(db.exec(select(Book.isbn)).all())
    added_count = 0

    for title, author, publisher, isbn, price in BOOKS_50:
        if isbn not in existing_isbns:
            new_book = Book(
                id=uuid4(),
                title=title,
                author=author,
                publisher=publisher,
                isbn=isbn,
                base_price=price,
                is_active=True,
                published_date=date(2024, 1, 15)
            )
            db.add(new_book)
            db.flush()  # book.id 확보 (아래 입고 관문이 참조한다)

            # 재고는 Inventory 행으로 심는다. virtual_stock 직접 대입은 SSOT를 우회해
            # "카탈로그에는 있는데 어디에도 없는 재고"를 만든다.
            fasttrack_new_stock_inbound(db, new_book, random.randint(2, 8), worker_id="SEED")

            existing_isbns.add(isbn)
            added_count += 1

    db.commit()
    print(f"Successfully seeded {added_count} new books into PostgreSQL DB!")
    total_books = len(db.exec(select(Book)).all())
    print(f"Total Books currently in DB: {total_books} books.")
